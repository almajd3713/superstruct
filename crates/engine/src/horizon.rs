//! The SDF horizon: WGSL port of the L1 rules (`shaders/horizon.wgsl`) and the tables it needs.
//!
//! The port must agree with `worldgen`, so everything derived from floats on the CPU side
//! (chances, deck weights) is computed here by the generator's own functions and handed to the
//! shader as exact integers, and the style table is generated from `worldgen::regime::STYLES`.

use std::fmt::Write;

use worldgen::l1::{chasm_chance, deck_weights, shaft_chance, trunk_chance};
use worldgen::regime::{RARE_STAIR_PER_MILLE, STYLES};

pub const SOURCE: &str = include_str!("../shaders/horizon.wgsl");
pub const PROBE_SOURCE: &str = include_str!("../shaders/horizon_probe.wgsl");

/// `k / 2^24 < p` over the 24 random bits `k`, as `k < ceil(p * 2^24)`: exact in f64.
#[allow(clippy::cast_sign_loss)] // p is a probability, never negative
fn threshold(p: f32) -> u32 {
    (f64::from(p) * 16_777_216.0).ceil() as u32
}

fn table(out: &mut String, name: &str, ty: &str, values: &[String]) {
    let _ = writeln!(
        out,
        "var<private> {name}: array<{ty}, {}> = array<{ty}, {}>({});",
        values.len(),
        values.len(),
        values.join(", ")
    );
}

/// The generated tables, to be placed before `horizon.wgsl`.
pub fn prelude() -> String {
    let mut out = String::from("// Generated by horizon::prelude. Do not edit.\n");
    let _ = writeln!(
        out,
        "const RARE_STAIR_PER_MILLE: u32 = {RARE_STAIR_PER_MILLE}u;"
    );
    let u = |v: u32| format!("{v}u");
    let pair = |(lo, hi): (u8, u8)| format!("vec2<i32>({lo}, {hi})");
    table(
        &mut out,
        "STYLE_W",
        "u32",
        &STYLES.iter().map(|s| u(s.weight)).collect::<Vec<_>>(),
    );
    table(
        &mut out,
        "STYLE_D",
        "vec2<i32>",
        &STYLES.iter().map(|s| pair(s.density)).collect::<Vec<_>>(),
    );
    table(
        &mut out,
        "STYLE_V",
        "vec2<i32>",
        &STYLES
            .iter()
            .map(|s| pair(s.verticality))
            .collect::<Vec<_>>(),
    );
    let all = 0..=255u8;
    table(
        &mut out,
        "TRUNK_T",
        "u32",
        &all.clone()
            .map(|v| u(threshold(trunk_chance(v))))
            .collect::<Vec<_>>(),
    );
    table(
        &mut out,
        "SHAFT_T",
        "u32",
        &all.clone()
            .map(|d| u(threshold(shaft_chance(d))))
            .collect::<Vec<_>>(),
    );
    table(
        &mut out,
        "CHASM_T",
        "u32",
        &all.clone()
            .map(|d| u(threshold(chasm_chance(d))))
            .collect::<Vec<_>>(),
    );
    table(
        &mut out,
        "DECK_W",
        "u32",
        &all.flat_map(|d| deck_weights(d).map(u)).collect::<Vec<_>>(),
    );
    out
}

/// Prelude plus port, ready to compile.
pub fn source() -> String {
    format!("{}\n{SOURCE}", prelude())
}

/// Prelude, port and the probe entry point.
pub fn probe_source() -> String {
    format!("{}\n{PROBE_SOURCE}", source())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn thresholds_match_the_float_comparison() {
        // For every table entry, `k / 2^24 < p` and `k < threshold` agree around the edge.
        for v in 0..=255u8 {
            for p in [trunk_chance(v), shaft_chance(v), chasm_chance(v)] {
                let t = threshold(p);
                for k in [t.saturating_sub(2), t.saturating_sub(1), t, t + 1] {
                    assert_eq!((k as f32 / 16_777_216.0) < p, k < t, "p {p} k {k} t {t}");
                }
            }
        }
    }

    #[test]
    fn prelude_has_every_table() {
        let p = prelude();
        for name in [
            "STYLE_W", "STYLE_D", "STYLE_V", "TRUNK_T", "SHAFT_T", "CHASM_T", "DECK_W",
        ] {
            assert!(p.contains(&format!("var<private> {name}")), "{name}");
        }
    }
}
